function buildRunHistory() {
  const runs = RUN_DEFS.map((def, runIndex) => {
    const rowScale = 1 + runIndex * 0.02;
    const sources = SOURCE_DEFS.map((source) => {
      const rowsFetched = Math.round(source.base * 1000 * rowScale);
      const inserted =
        runIndex === 0 ? rowsFetched : Math.round(source.base * between(3, 40));
      const updated = runIndex === 0 ? 0 : Math.round(source.base * between(1, 22));
      const unchanged = Math.max(rowsFetched - inserted - updated, 0);
      return {
        source: source.source,
        rows_fetched: rowsFetched,
        inserted,
        updated,
        unchanged,
        delta_vs_previous: runIndex === 0 ? rowsFetched : inserted,
        artifact_sha256: fakeSha256(`${def.id}-${source.source}`),
        source_url: source.url,
        limitations: source.limitations,
      };
    });

    return {
      run_id: def.id,
      started_at: isoMinus(def.startedOffsetH),
      finished_at: isoMinus(def.startedOffsetH, intBetween(7, 34)),
      trigger: def.trigger,
      git_sha: fakeSha256(def.id).slice(0, 40),
      sources,
      artifacts: ARTIFACT_DEFS.map((artifact) => {
        const ipnsName = fakeIpnsName(artifact.label);
        return {
          name: artifact.name,
          cid: fakeCid("bafybeisample", 59),
          ipns_label: artifact.label,
          ipns_name: ipnsName,
          gateway_url: `https://ipfs.filebase.io/ipns/${ipnsName}/${artifact.name}`,
        };
      }),
      note: SAMPLE_NOTE,
    };
  });

  return {
    county: "duval",
    generatedAt: NOW.toISOString(),
    note: SAMPLE_NOTE,
    runs,
  };
}

function buildCoverage(runHistory, parcelRows) {
  const latest = runHistory.runs[runHistory.runs.length - 1];
  const expected = {
    appraisal: 421000,
    sales: 104000,
    addresses: 62000,
    permits: 48000,
    contractors: 14000,
    sunbiz: 18500,
    places: 7100,
    transit: 3200,
    hydrography: 2100,
  };
  return {
    county: "duval",
    exportedAt: NOW.toISOString(),
    note: SAMPLE_NOTE,
    query_table_rows: parcelRows,
    datasets: latest.sources.map((source) => ({
      county: "duval",
      source: source.source,
      ingested_count: source.rows_fetched,
      expected_count: expected[source.source] ?? null,
      first_loaded_at: runHistory.runs[0].started_at,
      last_loaded_at: latest.finished_at,
      cid: fakeCid("bafybeisample", 59),
      ipns_label: `oracle-${source.source}-duval`,
    })),
  };
}

function buildCatalog(runHistory) {
  const artifacts = runHistory.runs[runHistory.runs.length - 1].artifacts;
  const find = (name) => artifacts.find((artifact) => artifact.name === name) ?? null;
  const queryTable = find("query-table.parquet");
  const coverage = find("dataset-coverage.json");
  return {
    schemaVersion: "1.0",
    generatedAt: NOW.toISOString(),
    note: SAMPLE_NOTE,
    counties: [
      {
        countyKey: "duval",
        countyName: "Duval",
        stateCode: "FL",
        countyFips: "12031",
        status: "published",
        queryTableUrl: queryTable ? `https://ipfs.filebase.io/ipns/${queryTable.ipns_name}` : null,
        datasetCoverageUrl: coverage
          ? `https://ipfs.filebase.io/ipns/${coverage.ipns_name}/dataset-coverage.json`
          : null,
        permitQueryTableUrl: null,
        placesTableUrl: null,
        updatedAt: NOW.toISOString(),
      },
    ],
  };
}

/**
 * The published artifacts index, in the shape pipeline/src/publish/index.ts writes it: one entry
 * per published object, keyed by the object name the run records carry as `path`, carrying the
 * gateway URL and the IPNS name the publish step produced. The UI joins run artifacts to this so
 * the cards can show a URL instead of "not available".
 *
 * Derived from the sample run history rather than generated fresh, so the CIDs and IPNS names on
 * both sides agree and the join actually matches in the sample runtime, exactly as it does
 * against the published index.
 */
function buildArtifactsIndex(runHistory) {
  const artifacts = runHistory.runs[runHistory.runs.length - 1].artifacts;
  return {
    county: "duval",
    generatedAt: NOW.toISOString(),
    mode: "published",
    note: SAMPLE_NOTE,
    gateway: "https://ipfs.filebase.io",
    artifacts: artifacts.map((artifact) => ({
      name: artifact.name,
      key: `sample/duval/${artifact.name}`,
      contentType: artifact.name.endsWith(".parquet")
        ? "application/vnd.apache.parquet"
        : "application/json",
      bytes: null,
      sha256: null,
      cid: artifact.cid,
      cidV1: artifact.cid,
      url: `https://ipfs.filebase.io/ipfs/${artifact.cid}`,
      ipnsLabel: artifact.ipns_label,
      ipnsName: artifact.ipns_name,
      ipnsUrl: `https://ipfs.filebase.io/ipns/${artifact.ipns_name}`,
    })),
    ipns: Object.fromEntries(
      artifacts.map((artifact) => [
        artifact.ipns_label,
        {
          label: artifact.ipns_label,
          networkKey: artifact.ipns_name,
          cid: artifact.cid,
          gatewayUrl: `https://ipfs.filebase.io/ipns/${artifact.ipns_name}`,
        },
      ]),
    ),
  };
}

async function writeOpenData(rows) {
  await mkdir(join(OPEN_DATA_DIR, "shards"), { recursive: true });

  const sampled = rows.slice(0, 40);
  const shardSize = 20;
  const shards = [];

  for (let start = 0; start < sampled.length; start += shardSize) {
    const slice = sampled.slice(start, start + shardSize);
    const shardName = `shard-${String(shards.length).padStart(4, "0")}.json`;
    shards.push({ shard: shardName, count: slice.length });
    await writeFile(
      join(OPEN_DATA_DIR, "shards", shardName),
      JSON.stringify(
        {
          note: SAMPLE_NOTE,
          properties: Object.fromEntries(slice.map((row) => [row.property_id, row.property_cid])),
        },
        null,
        2,
      ),
      "utf8",
    );
  }

  await writeFile(
    join(OPEN_DATA_DIR, "index.json"),
    JSON.stringify(
      {
        county: "duval",
        generatedAt: NOW.toISOString(),
        note: SAMPLE_NOTE,
        totalProperties: sampled.length,
        shards,
      },
      null,
      2,
    ),
    "utf8",
  );

  for (const row of sampled) {
    await writeFile(
      join(OPEN_DATA_DIR, `${row.property_cid}.json`),
      JSON.stringify(
        {
          note: SAMPLE_NOTE,
          property: {
            parcel_identifier: row.parcel_identifier,
            property_type: row.property_type,
            property_structure_built_year: row.built_year,
            livable_floor_area: row.livable_floor_area,
            area_under_air: row.livable_floor_area,
            subdivision: row.subdivision,
          },
          address: {
            street_address: row.address_street,
            city_name: row.address_city,
            postal_code: row.address_zip,
            state_code: row.state_code,
            county_name: row.county_name,
            latitude: row.latitude,
            longitude: row.longitude,
          },
          structure: {
            exterior_wall_material_primary: row.exterior_wall_material,
            roof_covering_material: row.roof_covering_material,
            roof_year_est: row.roof_year_est,
            roof_age_basis: row.roof_age_basis,
          },
          tax: {
            tax_year: CURRENT_YEAR,
            property_assessed_value_amount: row.assessed_value,
            property_market_value_amount: row.market_value,
            property_land_amount: row.land_value,
          },
          sales: row.last_sale_date_any
            ? [
                {
                  ownership_transfer_date: row.last_sale_date_any,
                  tenure_basis: row.tenure_basis,
                  purchase_price_amount: row.last_sale_price,
                },
              ]
            : [],
          owners: [
            {
              name: row.owner_name,
              region_class: row.owner_region_class,
              mailing_city: row.owner_mailing_city,
              mailing_state: row.owner_mailing_state,
            },
          ],
          provenance: {
            source_system: row.source_system,
            source_url: row.source_url,
            fetched_at: row.fetched_at,
            run_id: row.run_id,
          },
        },
        null,
        2,
      ),
      "utf8",
    );
  }

  return { shards: shards.length, properties: sampled.length };
}


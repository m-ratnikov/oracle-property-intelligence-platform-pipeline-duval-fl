/**
 * Generate the synthetic development dataset in public/sample.
 *
 * The UI must be runnable and demonstrable before the pipeline publishes its
 * first artifacts, so this writes files in exactly the published shapes:
 *
 *   public/sample/query-table.parquet     one row per parcel, canonical columns + extras
 *   public/sample/run-history.json        four runs with per source deltas and limitations
 *   public/sample/dataset-coverage.json   coverage snapshot
 *   public/sample/catalog.json            published counties catalog
 *   public/sample/artifacts-index.json    published artifacts index (CIDs, URLs, IPNS names)
 *   public/sample/open-data/index.json    sharded per property JSON index
 *   public/sample/open-data/shards/*.json
 *   public/sample/open-data/<cid>.json
 *
 * Every record is synthetic. The county key stays "duval" so the shapes match,
 * and each file carries a "note" field saying it is sample data. The UI shows a
 * SAMPLE badge whenever it is reading these files rather than published ones.
 *
 * Deterministic: a fixed seed means regenerating produces byte identical rows,
 * so the tests can assert on counts.
 */


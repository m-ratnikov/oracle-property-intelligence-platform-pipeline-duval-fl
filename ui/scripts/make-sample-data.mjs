function forSql(path) {
  return path.replace(/\\/g, "/").replace(/'/g, "''");
}

async function writeParquet(rows) {
  const staging = join(tmpdir(), `duval-sample-${Date.now()}.json`);
  await writeFile(staging, JSON.stringify(rows), "utf8");

  const instance = await DuckDBInstance.create(":memory:");
  const connection = await instance.connect();
  try {
    const projection = CASTS.map(
      ([name, type]) => `CAST("${name}" AS ${type}) AS "${name}"`,
    ).join(",\n  ");
    const target = join(OUT_DIR, "query-table.parquet");
    await connection.run(
      `COPY (
  SELECT
  ${projection}
  FROM read_json('${forSql(staging)}', format = 'array')
  ORDER BY property_id
) TO '${forSql(target)}' (FORMAT PARQUET, COMPRESSION ZSTD, ROW_GROUP_SIZE 20000)`,
    );

    const check = await connection.runAndReadAll(
      `SELECT COUNT(*) AS rows, COUNT(DISTINCT property_id) AS folios FROM read_parquet('${forSql(target)}')`,
    );
    const [countRow] = check.getRowObjects();
    return {
      rows: Number(countRow.rows),
      folios: Number(countRow.folios),
      path: target,
    };
  } finally {
    connection.closeSync();
    instance.closeSync();
    await rm(staging, { force: true });
  }
}


function weightedRegion() {
  const roll = rand();
  let cumulative = 0;
  for (const entry of OWNER_REGIONS) {
    cumulative += entry.weight;
    if (roll < cumulative) return entry.value;
  }
  return "LOCAL";
}

/* --------------------------------------------------------------- fake ids */

const BASE32 = "abcdefghijklmnopqrstuvwxyz234567";

function fakeCid(prefix, length) {
  let out = prefix;
  while (out.length < length) out += BASE32[Math.floor(rand() * BASE32.length)];
  return out;
}

function fakePropertyCid() {
  return fakeCid("bafkreisample", 59);
}

function fakeIpnsName(label) {
  const seedRand = mulberry32(
    [...label].reduce((acc, char) => (acc * 31 + char.charCodeAt(0)) >>> 0, 7),
  );
  let out = "k51qzi5uqu5d";
  while (out.length < 62) out += BASE32[Math.floor(seedRand() * BASE32.length)];
  return out;
}

function fakeSha256(seedText) {
  const seedRand = mulberry32(
    [...seedText].reduce((acc, char) => (acc * 33 + char.charCodeAt(0)) >>> 0, 11),
  );
  let out = "";
  while (out.length < 64) out += "0123456789abcdef"[Math.floor(seedRand() * 16)];
  return out;
}

